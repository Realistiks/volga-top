window.findBasicAnswer = function (question) {
  var text = String(question || '').toLowerCase()
    .replace(/[?.!,:;()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  var list = window.TEAM_ANSWERS || [];
  for (var i = 0; i < list.length; i += 1) {
    for (var j = 0; j < list[i].match.length; j += 1) {
      if (text.indexOf(list[i].match[j]) !== -1) return list[i].answer;
    }
  }
  return null;
};
